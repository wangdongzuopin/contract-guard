/**
 * 仿真合同语料库
 *
 * 真实合同拿不到，就自己造 —— 但必须造得**像**，否则测出来的精度没有意义。
 *
 * 三条自我约束：
 *
 * 1. **真值独立于规则实现**。偏离项是写在自然语言正文里的，
 *    期望命中的规则由人工标注，不是从 Rule 对象推导出来的。
 *    否则就是自己测自己，精度永远是 100%。
 *
 * 2. **必须包含负样本**。每份「合规合同」故意把红线卡在**边界值**
 *    （账期正好 60 天、违约金正好 10%、保密正好 3 年），
 *    引擎若用 `>=` 而不是 `>`，就会在干净合同上疯狂误报。
 *
 * 3. **必须包含触发条件样本**。后付款、不涉个人数据的合同，
 *    不该被要求写「付款担保」「数据合规」——
 *    这类规则若无触发词，会在每一份合同上报警，久而久之就是噪声。
 *
 * 排版上刻意模仿真实 PDF：固定行宽硬换行（会把词劈开）、
 * 编号体系混用、条款首行可能很短（触发标题/正文判定）。
 */

export interface CorpusClause {
  /** 条款首行，如「第三条 付款与结算」 */
  head: string;
  /** 单独成行的标题（可选） */
  title?: string;
  /** 正文段落 */
  body: string[];
}

export interface ExpectedFinding {
  ruleId: string;
  /**
   * 期望的实际值。
   *   限值类 —— 合同里写的数值（如「120 日」「20%」）
   *   禁用类 —— 命中的禁用表述（如「全部归甲方」）
   *   缺失类 —— 不填（此时 actual 是「期望包含哪些词」，不是发现本身）
   */
  actual?: string;
  /** 期望定位到的条款编号 */
  clause?: string;
}

export interface CorpusContract {
  id: string;
  fileName: string;
  title: string;
  docType: DocumentType;
  /** 抬头（甲方/乙方/编号等） */
  header: string[];
  clauses: CorpusClause[];
  /**
   * 期望的发现列表 —— 精确匹配，多一条算误报，少一条算漏报。
   * 按 (规则, 实际值) 比对，只比规则集合会漏掉「同一条规则报错了数值」。
   */
  expect: ExpectedFinding[];
  /** 这份样本要验证什么 */
  note: string;
}

