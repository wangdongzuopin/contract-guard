/** 真实 A4 合同正文的行宽（字符数）—— 硬换行会把词劈开 */
export const LINE_WIDTH = 38;

/**
 * 把合同结构渲染成「带换行的纯文本」，模仿 PDF 行重组后的形态。
 *
 * 关键：换行位置**不避开词语**。真实中文 PDF 排版就是这样，
 * 「不可抗力」完全可能被拆成「不可抗」+「力」。引擎必须扛得住。
 */
export function renderContractText(spec: CorpusContract, width = LINE_WIDTH): string {
  const out: string[] = [];

  out.push(spec.title);
  out.push(...spec.header);
  out.push('');

  for (const c of spec.clauses) {
    out.push(c.head);
    if (c.title) out.push(c.title);
    for (const p of c.body) {
      for (const line of wrap(p, width)) out.push(line);
    }
    out.push('');
  }

  return out.join('\n');
}

/** 硬换行：按字符数切，不考虑词语边界 */
function wrap(text: string, width: number): string[] {
  const lines: string[] = [];
  let cur = '';
  for (const ch of text) {
    cur += ch;
    if (cur.length >= width) {
      lines.push(cur);
      cur = '';
    }
  }
  if (cur) lines.push(cur);
  return lines;
}

/**
 * 渲染成 A4 合同样式的 HTML —— 交给无头浏览器打印成 PDF。
 *
 * 与 `renderContractText` 的区别：这里**不预先硬换行**，
 * 让浏览器按真实版心宽度自然折行。折行位置由排版决定，
 * 会把词劈开（这正是要测的），但具体位置与文本层测试不同 ——
 * 所以 PDF 层要单独跑一遍，验证解析链路不丢内容。
 */
export function renderContractHtml(spec: CorpusContract): string {
  const esc = (s: string) =>
    s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

  const body: string[] = [];
  body.push(`<h1>${esc(spec.title)}</h1>`);
  body.push(`<div class="meta">${spec.header.map((h) => `<p>${esc(h)}</p>`).join('')}</div>`);

  for (const c of spec.clauses) {
    body.push(`<h2>${esc(c.head)}</h2>`);
    if (c.title) body.push(`<h3>${esc(c.title)}</h3>`);
    for (const p of c.body) body.push(`<p>${esc(p)}</p>`);
  }

  return `<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<title>${esc(spec.title)}</title>
<style>
  /* 仿真语料使用仓库中的开源字体子集，确保样本可分发。 */
  @font-face { font-family: "合同仿真示例字体"; src: url("../../fonts/contract-guard-fixture-font.otf") format("opentype"); font-style: normal; font-weight: 100 900; }
  @page { size: A4; margin: 22mm 20mm; }
  body {
    /* 仿真文档使用开源字体，便于随项目分发。 */
    font-family: "合同仿真示例字体", sans-serif;
    font-size: 10.5pt;
    line-height: 1.8;
    margin: 0;
    color: #000;
  }
  h1 { font-size: 16pt; text-align: center; margin: 0 0 10pt; font-weight: bold; }
  h2 { font-size: 10.5pt; margin: 14pt 0 4pt; font-weight: bold; }
  h3 { font-size: 10.5pt; margin: 6pt 0 2pt; font-weight: bold; }
  p { margin: 0 0 4pt; text-indent: 2em; text-align: justify; }
  .meta p { text-indent: 0; margin: 0 0 2pt; }
</style>
</head>
<body>
${body.join('\n')}
</body>
</html>`;
}
